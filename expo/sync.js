// Copies the built Wakha page into wakha-html.js. Run after every build of the app: npm run sync
const fs = require("fs"), path = require("path");
const src = path.join(__dirname, "..", "dist", "preview.html");
const html = fs.readFileSync(src, "utf8");
fs.writeFileSync(path.join(__dirname, "wakha-html.js"), "// generated by sync.js, do not edit\nexport default " + JSON.stringify(html) + ";\n");
console.log("wakha-html.js", (html.length / 1e6).toFixed(2), "MB");
